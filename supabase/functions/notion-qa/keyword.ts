const PUNCT = /[，。！？、：；「」『』（）()[\]{}~!@#$%^&*_+=|\\/<>,.?:;'"`\s\-—～]/g;

function toSimplified(input: string): string {
  return Array.from(input).map((c) => T2S[c] ?? c).join("");
}

/** 回傳用來查 Notion 的關鍵字；抓不到可用詞時回空字串（呼叫端要處理查無資料） */
export function extractKeyword(question: string): string {
  let s = toSimplified(question).replace(PUNCT, "");

  // 先看有沒有命中主題詞，取最長的（「大腿内侧」優先於「大腿」）
  const hits = TOPICS.filter((t) => s.includes(t));
  if (hits.length > 0) {
    hits.sort((a, b) => b.length - a.length);
    return hits[0];
  }

  // 沒命中才退回切詞：去停用詞後取最長中文片段，砍到 2~3 字
  for (const w of STOP) {
    s = s.split(toSimplified(w)).join("");
  }
  const segs = (s.match(/[一-鿿]+/g) ?? []).sort((a, b) => b.length - a.length);
  let keyword = segs[0] ?? "";
  if (keyword.length > 3) keyword = keyword.slice(0, 2);
  return keyword;
}
